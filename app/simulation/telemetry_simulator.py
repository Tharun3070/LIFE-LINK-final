"""Ambulance GPS Telemetry Simulator for LifeLink Local Development and Testing.

CRITICAL SAFETY DESIGN:
- All events generated by this simulator are explicitly tagged with `telemetrySource="simulated"`.
- Device ID is prefixed with `SIM-DEVICE-`.
- Telemetry generated by this module cannot be confused with genuine hardware GPS data.
"""
from datetime import datetime, timezone, timedelta
from typing import List, Dict, Any, Optional
from app.schemas.ambulance import AmbulanceTelemetryIngest


# Predefined realistic ambulance response route in Bengaluru (from Indiranagar to Apollo Hospital Jayanagar)
SIMULATED_ROUTE_WAYPOINTS = [
    (12.9784, 77.6408, 180.0, 42.0), # Indiranagar 100ft Rd
    (12.9698, 77.6385, 195.0, 48.0), # Domlur Flyover
    (12.9554, 77.6300, 210.0, 52.0), # Intermediate Ring Road
    (12.9352, 77.6245, 230.0, 45.0), # Koramangala 80ft Road
    (12.9250, 77.6100, 245.0, 38.0), # Dairy Circle
    (12.9165, 77.5925, 260.0, 32.0), # Jayanagar 4th Block
    (12.9090, 77.5850, 270.0, 25.0), # Apollo Hospital Trauma Bay
]


def generate_simulated_telemetry_packet(
    ambulance_id: str,
    step_index: int = 0,
    base_time: Optional[datetime] = None,
    device_id: str = "SIM-DEVICE-AMB-01",
) -> AmbulanceTelemetryIngest:
    """Generates a single simulated GPS telemetry packet explicitly marked as 'simulated'."""
    idx = step_index % len(SIMULATED_ROUTE_WAYPOINTS)
    lat, lng, heading, speed = SIMULATED_ROUTE_WAYPOINTS[idx]

    t = base_time or datetime.now(timezone.utc)
    step_time = t + timedelta(seconds=step_index * 5)

    return AmbulanceTelemetryIngest(
        ambulanceId=ambulance_id,
        deviceId=device_id,
        lat=lat,
        lng=lng,
        heading=heading,
        speedKmh=speed,
        altitudeMeters=920.0 + (step_index * 1.5),
        deviceTimestamp=step_time.isoformat(),
        telemetrySource="simulated", # Unmistakably marked as simulated
    )


def generate_simulated_telemetry_batch(
    ambulance_id: str,
    count: int = 5,
    interval_seconds: int = 5,
    start_time: Optional[datetime] = None,
    device_id: str = "SIM-DEVICE-AMB-01",
) -> List[AmbulanceTelemetryIngest]:
    """Generates a sequential series of simulated telemetry packets."""
    t0 = start_time or datetime.now(timezone.utc)
    batch = []
    for i in range(count):
        packet = generate_simulated_telemetry_packet(
            ambulance_id=ambulance_id,
            step_index=i,
            base_time=t0,
            device_id=device_id,
        )
        batch.append(packet)
    return batch
